// Command sourcemd writes docs/SOURCE.md from go.mod, tools/rootwatch/go.mod
// and the notes below (VAULT-SERVICE-INDEPENDENCE S2: the hand-kept file
// went stale). Run it from the repository root after changing a
// dependency:
//
//	go run ./internal/sourcemd -w
//
// Without -w it prints the file. TestSourceMDUpToDate fails while the
// committed file differs, or while a direct dependency has no note here
// (or a note names a module no longer required).
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// note is what go.mod does not say about a direct dependency.
type note struct {
	// Why, for VettID's own modules: what the service takes from it.
	Why string
	// Licence (SPDX) and UsedBy, for every other module.
	Licence string
	UsedBy  string
}

// notes are the service module's direct dependencies.
