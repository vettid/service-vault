const header = `# Pinned sources

<!-- Generated by ` + "`go run ./internal/sourcemd -w`" + ` from go.mod, tools/rootwatch/go.mod and
the notes in internal/sourcemd/main.go. Do not edit by hand; TestSourceMDUpToDate fails while
this file differs. -->

The service vault builds on vettid-vault's wire packages (` + "`vms/*`" + `) and
vettid-relay's ` + "`relayclient`" + ` instead of reimplementing the protocol
(MEMBER-SERVICE-PLAN §7.2). They are pinned in ` + "`go.mod`" + `; a change to a
pin is its own PR, with any vectors copied from the new commit and their
tests passing (VAULT-SERVICE-INDEPENDENCE R5).
`

func main() {
	write := flag.Bool("w", false, "write docs/SOURCE.md instead of printing it")
	flag.Parse()
	out, err := render(".")
	if err != nil {
		fmt.Fprintln(os.Stderr, "sourcemd:", err)
		os.Exit(1)
	}
	if !*write {
		os.Stdout.Write(out)
		return
	}
	if err := os.WriteFile(filepath.Join("docs", "SOURCE.md"), out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "sourcemd:", err)
		os.Exit(1)
	}
}

// render builds SOURCE.md for the repository at root.
func render(root string) ([]byte, error) {
	main, err := directRequires(filepath.Join(root, "go.mod"))
	if err != nil {
		return nil, err
	}
	tools, err := directRequires(filepath.Join(root, "tools", "rootwatch", "go.mod"))
	if err != nil {
		return nil, err
	}
	if err := matchNotes("go.mod", main, notes); err != nil {
		return nil, err
	}
	if err := matchNotes("tools/rootwatch/go.mod", tools, rootwatchNotes); err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("\n## VettID modules\n\n")
	b.WriteString("| Module | Version in `go.mod` | Commit | Date (UTC) | What the service takes |\n|---|---|---|---|---|\n")
	for _, r := range main {
		if !own(r.path) {
			continue
		}
		commit, date := "(tag)", ""
		if p, ok := pseudo(r.version); ok {
			commit = fmt.Sprintf("[`%s`](https://%s/commit/%s)", p.commit, r.path, p.commit)
			date = p.date
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n", r.path, r.version, commit, date, notes[r.path].Why)
	}
	b.WriteString("\n## Other direct dependencies\n\n")
	b.WriteString("Ordinary releases chosen in the PR that adds them, with their licence checked for AGPL-3.0 compatibility. A version that is a commit, not a tag, says so.\n\n")
	table(&b, main, notes, func(r require) bool { return !own(r.path) })
	b.WriteString("\n## tools/rootwatch (its own module)\n\n")
	b.WriteString("Not part of the service's build: the daily `vault-roots` workflow runs it (`internal/vaultroots`).\n\n")
	table(&b, tools, rootwatchNotes, func(require) bool { return true })
	return b.Bytes(), nil
}

func table(b *bytes.Buffer, rs []require, ns map[string]note, keep func(require) bool) {
	b.WriteString("| Module | Version | Licence | Used by |\n|---|---|---|---|\n")
	for _, r := range rs {
		if !keep(r) {
			continue
		}
		v := "`" + r.version + "`"
		if p, ok := pseudo(r.version); ok {
			v += fmt.Sprintf(" (commit `%s`, %s)", p.commit, p.date[:10])
		}
		n := ns[r.path]
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", r.path, v, n.Licence, n.UsedBy)
	}
}

func own(path string) bool { return strings.HasPrefix(path, "github.com/vettid/") }

// matchNotes requires a note for every direct requirement and a direct
// requirement for every note, each of the right kind.
func matchNotes(file string, rs []require, ns map[string]note) error {
	var errs []error
	seen := map[string]bool{}
	for _, r := range rs {
		seen[r.path] = true
		n, ok := ns[r.path]
		switch {
		case !ok:
			errs = append(errs, fmt.Errorf("%s requires %s directly, but internal/sourcemd has no note for it", file, r.path))
		case own(r.path) && n.Why == "":
			errs = append(errs, fmt.Errorf("%s: the note needs Why", r.path))
		case !own(r.path) && (n.Licence == "" || n.UsedBy == ""):
			errs = append(errs, fmt.Errorf("%s: the note needs Licence and UsedBy", r.path))
		}
	}
	for path := range ns {
		if !seen[path] {
			errs = append(errs, fmt.Errorf("internal/sourcemd has a note for %s, which %s does not require directly", path, file))
		}
	}
	sort.Slice(errs, func(i, j int) bool { return errs[i].Error() < errs[j].Error() })
	return errors.Join(errs...)
}

type require struct{ path, version string }

// directRequires reads the direct requirements of a go.mod, sorted by
// path. It knows only the directives this repository uses and refuses
// any other, so a replace or exclude can't slip past the generated file.
func directRequires(file string) ([]require, error) {
	f, err := os.Open(file)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []require
	inBlock := ""
	sc := bufio.NewScanner(f)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		code, comment, _ := strings.Cut(line, "//")
		code = strings.TrimSpace(code)
		indirect := strings.TrimSpace(comment) == "indirect"
		switch {
		case code == "":
			continue
		case inBlock != "" && code == ")":
			inBlock = ""
			continue
		case inBlock == "require":
			f := strings.Fields(code)
			if len(f) != 2 {
				return nil, fmt.Errorf("%s:%d: unexpected require line %q", file, n, line)
			}
			if !indirect {
				out = append(out, require{f[0], f[1]})
			}
			continue
		case inBlock != "":
			continue
		}
		f := strings.Fields(code)
		switch f[0] {
		case "module", "go", "toolchain", "ignore":
			if len(f) == 2 && f[1] == "(" {
				inBlock = f[0]
			}
		case "require":
			switch {
			case len(f) == 2 && f[1] == "(":
				inBlock = "require"
			case len(f) == 3:
				if !indirect {
					out = append(out, require{f[1], f[2]})
				}
			default:
				return nil, fmt.Errorf("%s:%d: unexpected require line %q", file, n, line)
			}
		default:
			return nil, fmt.Errorf("%s:%d: directive %q is not handled by internal/sourcemd; extend it", file, n, f[0])
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if inBlock != "" {
		return nil, fmt.Errorf("%s: unterminated %s block", file, inBlock)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].path < out[j].path })
	return out, nil
}

type pseudoVersion struct{ commit, date string }

var pseudoRE = regexp.MustCompile(`^v[0-9]+\.[0-9]+\.[0-9]+-(?:[0-9A-Za-z.]+\.)?([0-9]{14})-([0-9a-f]{12})(?:\+incompatible)?$`)

// pseudo reads a pseudo-version's commit and time (Go modules reference,
// "Pseudo-versions").
func pseudo(v string) (pseudoVersion, bool) {
	m := pseudoRE.FindStringSubmatch(v)
	if m == nil {
		return pseudoVersion{}, false
	}
	t := m[1]
	return pseudoVersion{commit: m[2], date: fmt.Sprintf("%s-%s-%s %s:%s:%s", t[0:4], t[4:6], t[6:8], t[8:10], t[10:12], t[12:14])}, true
}
